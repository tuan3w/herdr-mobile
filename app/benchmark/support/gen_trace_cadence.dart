// Regenerates `trace_cadence.dart` (the recorded chunk cadence per agent that
// the stream bench replays; a device build cannot read the fixtures):
//
//   cd app && dart run benchmark/support/gen_trace_cadence.dart
//
// `autoresearch-stream.sh` runs it before every build, and
// `test/traces_test.dart` fails when the checked-in file differs from what the
// fixtures give.
// ignore_for_file: avoid_print
import 'dart:io';

import 'trace_replay.dart';

const _fixtures = 'test/fixtures/traces';
const _output = 'benchmark/support/trace_cadence.dart';

/// `agent -> [gap, chars, ...]` of every `*.jsonl` under [dir], scenarios in
/// name order.
Map<String, List<int>> cadenceByAgent(Directory dir) {
  final out = <String, List<int>>{};
  final agents = dir.listSync().whereType<Directory>().toList()..sort((a, b) => a.path.compareTo(b.path));
  for (final agent in agents) {
    final files = agent.listSync().whereType<File>().where((f) => f.path.endsWith('.jsonl')).toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    final cadence = cadenceOf([for (final f in files) textChunks(parseTrace(f.readAsStringSync()))]);
    if (cadence.isNotEmpty) out[agent.uri.pathSegments.lastWhere((s) => s.isNotEmpty)] = cadence;
  }
  return out;
}

String render(Map<String, List<int>> cadence) {
  final b = StringBuffer()
    ..writeln('// GENERATED by benchmark/support/gen_trace_cadence.dart from test/fixtures/traces.')
    ..writeln('// Do not edit; run `cd app && dart run benchmark/support/gen_trace_cadence.dart`.')
    ..writeln()
    ..writeln('/// The recorded text-chunk cadence of each agent, every scenario of its traces in')
    ..writeln('/// name order, as flat `[gap, chars, gap, chars, ...]`: the gap since the previous')
    ..writeln('/// chunk in tenths of a millisecond (0 where a stream starts or a pause of 1 s or')
    ..writeln('/// more was cut) and the chunk size in characters.')
    ..writeln('const traceCadence = <String, List<int>>{');
  for (final e in cadence.entries) {
    b.writeln("  '${e.key}': [");
    for (var i = 0; i < e.value.length; i += 16) {
      final end = i + 16 > e.value.length ? e.value.length : i + 16;
      b.writeln('    ${e.value.sublist(i, end).join(', ')},');
    }
    b.writeln('  ],');
  }
  b.writeln('};');
  return b.toString();
}

void main() {
  final dir = Directory(_fixtures);
  if (!dir.existsSync()) {
    stderr.writeln('run this from the app/ directory: $_fixtures not found');
    exit(64);
  }
  File(_output).writeAsStringSync(render(cadenceByAgent(dir)));
  print('wrote $_output');
}
